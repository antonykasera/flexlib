#include "bench.h"
#include <stdio.h>
#include <string.h>

/* golden_gen links no golden.c of its own */
const BenchGolden bench_golden[] = {{"", 0U}};
const unsigned bench_golden_n = 0U;

static uint32_t cyc[BENCH_N];

int main(void) {
  bench_inputs_init();

  /* names must be unique, since the board looks hashes up by name */
  static const char *names[1024];
  unsigned n = 0U;
  for (unsigned g = 0U; g < bench_groups_n; g++) {
    for (unsigned i = 0U; i < bench_groups[g]->n && n < 1024U; i++) {
      names[n++] = bench_groups[g]->cases[i].name;
    }
  }
  for (unsigned a = 0U; a < n; a++) {
    for (unsigned b = 0U; b < a; b++) {
      if (strcmp(names[a], names[b]) == 0) {
        fprintf(stderr, "duplicate case name: %s\n", names[a]);
        return 1;
      }
    }
  }

  printf("/**\n"
         " * @file golden.c\n"
         " * @brief Output hashes of the golden bench cases, from the host "
         "build\n"
         " *\n"
         " * Generated by `make golden`; do not edit.\n"
         " *\n"
         " * Copyright (c) 2026 Antony Kasera\n"
         " * SPDX-License-Identifier: MIT\n"
         " */\n\n"
         "#include \"bench.h\"\n\n"
         "const BenchGolden bench_golden[] = {\n");
  for (unsigned g = 0U; g < bench_groups_n; g++) {
    for (unsigned i = 0U; i < bench_groups[g]->n; i++) {
      const BenchCase *c = &bench_groups[g]->cases[i];
      if (c->golden) {
        printf("    {\"%s\", 0x%08XU},\n", c->name, (unsigned)c->fn(cyc));
      }
    }
  }
  printf("};\n\n"
         "const unsigned bench_golden_n = BENCH_COUNT(bench_golden);\n");
  return 0;
}
